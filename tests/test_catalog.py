"""Unit tests for standalone species catalog generation (pipeline/catalog.py) and failure-safe staging."""
from __future__ import annotations

import json
from pathlib import Path
import tempfile
from unittest.mock import patch

from pipeline import catalog


ROOT = Path(__file__).resolve().parent.parent


def test_catalog_contains_all_species_profiles():
    species_dir = ROOT / "data/species"
    expected_files = list(species_dir.glob("*.json"))

    cat = catalog.build_catalog(species_dir)

    assert cat["version"] == 1
    assert cat["total"] == len(expected_files)
    assert len(cat["species"]) == len(expected_files)


def test_catalog_species_ids_unique_and_stable():
    cat = catalog.build_catalog(ROOT / "data/species")
    species = cat["species"]

    ids = [s["id"] for s in species]
    assert len(ids) == len(set(ids)), "Species IDs in catalog must be unique"

    names = [s["name"] for s in species]
    assert names == sorted(names, key=lambda n: n.lower()), "Catalog species must be sorted by common name"

    for entry in species:
        assert "id" in entry and entry["id"]
        assert "name" in entry and entry["name"]
        assert "color" in entry
        assert "environment" in entry
        assert "model" in entry


def test_adding_species_profile_updates_catalog():
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)

        # Copy existing profiles
        for p in (ROOT / "data/species").glob("*.json"):
            (tmp_path / p.name).write_text(p.read_text(encoding="utf-8"), encoding="utf-8")

        initial_cat = catalog.build_catalog(tmp_path)
        initial_count = initial_cat["total"]

        # Create new profile
        new_profile = {
            "schema_version": 1,
            "id": "test-super-fish",
            "common_name": "Test Super Fish",
            "scientific_name": "Superus pisces",
            "environment": "saltwater",
            "model": "grid",
            "display": {"color": "#ff00ff"},
            "factors": []
        }
        (tmp_path / "test-super-fish.json").write_text(json.dumps(new_profile), encoding="utf-8")

        updated_cat = catalog.build_catalog(tmp_path)
        assert updated_cat["total"] == initial_count + 1
        assert any(s["id"] == "test-super-fish" for s in updated_cat["species"])


def test_catalog_generation_succeeds_without_noaa_data():
    # Catalog builder reads local JSON files and requires no network or ocean satellite grids
    cat = catalog.build_catalog(ROOT / "data/species", generated_utc="2026-01-01T00:00:00+00:00")
    assert cat["generated_utc"] == "2026-01-01T00:00:00+00:00"
    assert cat["total"] == 130


def test_catalog_main_cli():
    catalog.main()
    output_path = ROOT / "data/live/species_catalog.json"
    assert output_path.exists(), "data/live/species_catalog.json must be generated by main()"
    data = json.loads(output_path.read_text(encoding="utf-8"))
    assert data["version"] == 1
    assert data["total"] == 130
    assert len(data["species"]) == 130


def test_run_generates_catalog_on_layer_failure():
    from pipeline import run as run_mod
    with patch("pipeline.run.load_layers", return_value=None), \
         patch("pipeline.run.pull_buoys", return_value=[]), \
         patch("pipeline.run.load_forecast", return_value=None):
        run_mod.main()

    live = ROOT / "data/live"
    assert (live / "species_catalog.json").exists()
    cat_data = json.loads((live / "species_catalog.json").read_text(encoding="utf-8"))
    assert cat_data["total"] == 130

    latest_data = json.loads((live / "latest.json").read_text(encoding="utf-8"))
    assert latest_data["fish_updated"] is False
    assert any("satellite temperature could not be loaded" in err for err in latest_data["errors"])
    assert not (ROOT / "data/live_stage").exists(), "Temporary staging directory must be cleaned up"


def test_heatmap_partitioning_and_file_sizes():
    # 1. Test heatmap generator directly using temporary directory
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir)
        heat_json = {
            "width": 100,
            "height": 100,
            "bounds": [-120.0, 20.0, -110.0, 30.0],
            "note": "One byte per cell",
            "species": {
                "mahi-mahi": "AAAA",
                "red-snapper": "BBBB"
            }
        }
        now = "2026-01-01T00:00:00+00:00"

        # Manifest creation matching pipeline/run.py
        heat_manifest = {
            "version": 1,
            "generated_utc": now,
            "width": heat_json["width"],
            "height": heat_json["height"],
            "bounds": heat_json["bounds"],
            "note": heat_json["note"],
            "species": {sid: f"heat/{sid}.json" for sid in heat_json.get("species", {})}
        }
        manifest_file = tmp_path / "heat.json"
        manifest_file.write_text(json.dumps(heat_manifest, allow_nan=False, separators=(",", ":")), encoding="utf-8")

        heat_dir = tmp_path / "heat"
        heat_dir.mkdir(parents=True, exist_ok=True)
        for sid, b64_str in heat_json.get("species", {}).items():
            sp_heat = {
                "width": heat_json["width"],
                "height": heat_json["height"],
                "bounds": heat_json["bounds"],
                "scores_base64": b64_str
            }
            (heat_dir / f"{sid}.json").write_text(json.dumps(sp_heat, allow_nan=False, separators=(",", ":")), encoding="utf-8")

        # Validate manifest data integrity and format
        manifest_data = json.loads(manifest_file.read_text(encoding="utf-8"))
        assert manifest_data["version"] == 1
        assert manifest_data["width"] == 100
        assert manifest_data["height"] == 100
        assert "mahi-mahi" in manifest_data["species"]
        assert manifest_data["species"]["mahi-mahi"] == "heat/mahi-mahi.json"

        # Validate partition files exist and are below 100 MB limit
        for sid, rel_path in manifest_data["species"].items():
            partition_file = tmp_path / rel_path
            assert partition_file.exists(), f"Partition file {rel_path} referenced in manifest must exist"
            pdata = json.loads(partition_file.read_text(encoding="utf-8"))
            assert "scores_base64" in pdata
            assert partition_file.stat().st_size < 100 * 1024 * 1024

    # 2. If data/live/heat.json exists locally (e.g. after pipeline execution), validate its structure and partition sizes
    live_manifest = ROOT / "data/live/heat.json"
    if live_manifest.exists():
        manifest_size = live_manifest.stat().st_size
        assert manifest_size < 100 * 1024 * 1024, "data/live/heat.json manifest must be under 100 MB"
        mdata = json.loads(live_manifest.read_text(encoding="utf-8"))
        assert "species" in mdata
        for sid, rel_path in mdata.get("species", {}).items():
            pfile = ROOT / "data/live" / rel_path
            assert pfile.exists(), f"Referenced heat file {rel_path} must exist in data/live"
            size_mb = pfile.stat().st_size / (1024 * 1024)
            assert size_mb < 100, f"Heat file {pfile.name} is {size_mb:.2f} MB, which exceeds GitHub's 100 MB limit"
